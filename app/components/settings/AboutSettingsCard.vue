<script setup lang="ts">
import type { ApplicationDiagnostics } from '~/types/repository'
import ApplicationUpdatesCard from './ApplicationUpdatesCard.vue'

const { t } = useI18n()
const { notifySuccess, notifyError } = useNotificationService()

const diagnostics = ref<ApplicationDiagnostics | null>(null)
const isLoadingDiagnostics = ref<boolean>(false)
const isCopied = ref<boolean>(false)
const isExporting = ref<boolean>(false)

async function isTauriEnvironment(): Promise<boolean> {
  return typeof window !== 'undefined' && '__TAURI_INTERNALS__' in window
}

async function loadDiagnostics(): Promise<void> {
  isLoadingDiagnostics.value = true
  try {
    if (await isTauriEnvironment()) {
      const { invoke } = await import('@tauri-apps/api/core')
      diagnostics.value = await invoke<ApplicationDiagnostics>('get_application_diagnostics')
    } else {
      diagnostics.value = {
        app_version: '0.1.0',
        os_name: 'linux',
        os_arch: 'x86_64',
        git_binary_path: '/usr/bin/git',
        git_version: 'git version 2.43.0',
        current_repository_path: '/home/farshid/Desktop/self/gitverse',
      }
    }
  } catch (error) {
    console.error('Failed to load diagnostics:', error)
  } finally {
    isLoadingDiagnostics.value = false
  }
}

async function copyDiagnostics(): Promise<void> {
  if (!diagnostics.value) return

  const report = [
    '# GitVerse Diagnostics Report',
    `- Version: ${diagnostics.value.app_version}`,
    `- OS: ${diagnostics.value.os_name} (${diagnostics.value.os_arch})`,
    `- Git Path: ${diagnostics.value.git_binary_path}`,
    `- Git Version: ${diagnostics.value.git_version}`,
    `- Active Repository: ${diagnostics.value.current_repository_path || 'None'}`,
    `- Timestamp: ${new Date().toISOString()}`,
    '',
    '*Generated by GitVerse Diagnostics System. All tokens and credentials are safe and redacted.*',
  ].join('\n')

  try {
    await navigator.clipboard.writeText(report)
    isCopied.value = true
    notifySuccess(t('settings.about.diagnosticsCopied'))
    setTimeout(() => {
      isCopied.value = false
    }, 2000)
  } catch (error) {
    notifyError(String(error))
  }
}

async function exportDiagnosticsBundle(): Promise<void> {
  isExporting.value = true
  try {
    let bundle: unknown
    if (await isTauriEnvironment()) {
      const { invoke } = await import('@tauri-apps/api/core')
      bundle = await invoke('export_diagnostic_bundle')
    } else {
      bundle = {
        application_version: '0.1.0',
        operating_system: 'linux',
        architecture: 'x86_64',
        git_binary_path: '/usr/bin/git',
        git_version: 'git version 2.43.0',
        current_repository_path: '/home/farshid/Desktop/self/gitverse',
        generated_at_iso: new Date().toISOString(),
        connected_providers: [],
        recent_log_entries: [
          { timestamp: new Date().toISOString(), level: 'INFO', message: 'Diagnostics snapshot generated.' },
        ],
      }
    }

    const jsonString = JSON.stringify(bundle, null, 2)
    const blob = new Blob([jsonString], { type: 'application/json' })
    const downloadUrl = URL.createObjectURL(blob)
    const anchor = document.createElement('a')
    anchor.href = downloadUrl
    anchor.download = `gitverse-diagnostics-${new Date().toISOString().replace(/[:.]/g, '-')}.json`
    document.body.appendChild(anchor)
    anchor.click()
    document.body.removeChild(anchor)
    URL.revokeObjectURL(downloadUrl)

    notifySuccess(t('settings.about.diagnosticsExported'))
  } catch (error) {
    notifyError(String(error))
  } finally {
    isExporting.value = false
  }
}

onMounted(() => {
  void loadDiagnostics()
})
</script>

<template>
  <div class="space-y-4 text-xs">
    <!-- About Card -->
    <UCard>
      <div class="flex items-center gap-4 border-b border-default/70 pb-4">
        <SharedBrandLogo size="lg" />
        <div>
          <h2 class="text-base font-bold text-highlighted">
            GitVerse
          </h2>
          <p class="text-xs text-muted">
            {{ t('app.tagline') }}
          </p>
        </div>
      </div>

      <div class="divide-y divide-default/50 pt-2 font-mono text-[11px]">
        <div class="flex items-center justify-between py-2">
          <span class="text-muted font-sans">{{ t('settings.about.versionLabel') }}</span>
          <span class="text-highlighted">0.1.0 (Alpha Baseline)</span>
        </div>
        <div class="flex items-center justify-between py-2">
          <span class="text-muted font-sans">{{ t('settings.about.runtimeLabel') }}</span>
          <span class="text-highlighted">Tauri 2 + Rust + Nuxt 4 + Nuxt UI</span>
        </div>
        <div class="flex items-center justify-between py-2">
          <span class="text-muted font-sans">{{ t('settings.about.architectureLabel') }}</span>
          <span class="text-highlighted">Modular Monolith / Local-First (ADR-001 - ADR-004)</span>
        </div>
      </div>
    </UCard>

    <!-- In-App Software Updates Card -->
    <ApplicationUpdatesCard />

    <!-- Diagnostics Card -->
    <UCard>
      <div class="flex items-center justify-between border-b border-default/70 pb-3">
        <div class="flex items-center gap-2">
          <UIcon name="i-lucide-activity" class="h-4 w-4 text-primary" />
          <h3 class="text-sm font-semibold text-highlighted">
            {{ t('settings.about.diagnosticsTitle') }}
          </h3>
        </div>

        <div class="flex items-center gap-2">
          <UButton
            size="xs"
            color="neutral"
            variant="outline"
            icon="i-lucide-download"
            :label="t('settings.about.exportDiagnostics')"
            :loading="isExporting"
            @click="exportDiagnosticsBundle"
          />

          <UButton
            size="xs"
            :color="isCopied ? 'success' : 'neutral'"
            :variant="isCopied ? 'soft' : 'outline'"
            :icon="isCopied ? 'i-lucide-check' : 'i-lucide-copy'"
            :label="isCopied ? t('settings.about.copied') : t('settings.about.copyDiagnostics')"
            :loading="isLoadingDiagnostics"
            @click="copyDiagnostics"
          />
        </div>
      </div>

      <div v-if="diagnostics" class="divide-y divide-default/50 pt-2 font-mono text-[11px]">
        <div class="flex items-center justify-between py-1.5">
          <span class="text-muted font-sans">{{ t('settings.about.osArchLabel') }}</span>
          <span class="text-highlighted">{{ diagnostics.os_name }} / {{ diagnostics.os_arch }}</span>
        </div>
        <div class="flex items-center justify-between py-1.5">
          <span class="text-muted font-sans">{{ t('settings.about.gitVersionLabel') }}</span>
          <span class="text-highlighted">{{ diagnostics.git_version }}</span>
        </div>
        <div class="flex items-center justify-between py-1.5">
          <span class="text-muted font-sans">{{ t('settings.about.gitPathLabel') }}</span>
          <span class="text-highlighted truncate max-w-xs" :title="diagnostics.git_binary_path">{{ diagnostics.git_binary_path }}</span>
        </div>
      </div>

      <div class="mt-3 flex items-center gap-2 rounded-lg bg-muted/10 p-2 text-[10px] text-muted border border-default/50">
        <UIcon name="i-lucide-shield-check" class="h-4 w-4 shrink-0 text-success" />
        <span>{{ t('settings.about.diagnosticsPrivacyNote') }}</span>
      </div>
    </UCard>
  </div>
</template>
